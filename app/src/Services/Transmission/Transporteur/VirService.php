    public function normalizeArray(array $order, int $numberLine)
    {
        $this->recursiveArray($order);
        if (!empty($this->normalizeArray)) {
            if (in_array(strtolower((string) $this->normalizeArray['name']), array_map('strtolower', ProductReferenceInterface::REPOSSESS_REFS))) {
                $this->normalizeArray['contremarque'] = 'N';
                $this->normalizeArray['quantity'] = 1;
            } else {
                $this->normalizeArray['contremarque'] = 'C';
            }

            /**** Date ****/
            $this->normalizeArray['Numero de ligne'] = $numberLine;

            // code barre
            $this->normalizeArray['code barre'] = uniqid(sprintf('%d%d', $this->normalizeArray['taskId'], 1), true);

            // Vir retour context
            if (str_contains((string) $this->normalizeArray['taskId'], 'R')) {
                $this->normalizeArray['Trafic'] = 'R';
            } else {
                $this->normalizeArray['Trafic'] = 'L';
            }

            $array_replace = array_replace($this->headerLine, $this->normalizeArray);
            $new_line = ["\r\n", "\n", "\r"];
            foreach ($array_replace as $key => $line) {
                $line = str_replace($new_line, ' ', (string) $line);
                $array_replace[$key] = $line;
            }

            // found refacto dynamic solution
            $array_csv['header'] = $this->formatEnteteVir(array_slice($array_replace, 0, 5, true));
            $array_csv['orderLine'] = array_slice($array_replace, 5, 54, true);
            $array_csv['itemLine'] = array_slice($array_replace, 59, null, true);

            return $array_csv;
        }
    }

