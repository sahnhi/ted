    public function formatEnteteVir($entete): array
    {
        $formatedEntete = [];

        foreach ($entete as $item) {
            $formatedEntete[] = [$item];
        }

        return $formatedEntete;
    }

    public function generateTracking($number): string
    {
        return self::URL_TRACKING . ltrim((string) $number, 0);
    }
